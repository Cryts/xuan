/** 词 → 条目 的快速索引 */
export const FORBIDDEN_INDEX = new Map(FORBIDDEN.map((f) => [f.word, f]))

/**
 * 扫描一段文本，返回命中的禁用词。
 * 用于 content-lint 的全量扫描。
 */
export function scanText(text: string): ForbiddenEntry[] {
  const hits: ForbiddenEntry[] = []
  for (const f of FORBIDDEN) {
    if (text.includes(f.word)) hits.push(f)
  }
  return hits
}
